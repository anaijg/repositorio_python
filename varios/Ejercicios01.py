## Ejercicio 2 
numero1 = int(input("Número 1: "))
numero2 = int(input("Número 2: "))
numero3 = int(input("Número 3: "))
numero4 = int(input("Número 4: "))

print("Suma:", (numero1 + numero2 + numero3 + numero4))
print("Resta:", (numero1 - numero2 - numero3 - numero4))
print("Multiplicación:", (numero1 * numero2 * numero3 * numero4))
print("División:", (numero1 // numero2 // numero3 // numero4))
print("Módulo:", (numero1 % numero2 % numero3 % numero4))